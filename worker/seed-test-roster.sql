-- 本地测试名单夹具：把 participants 重置为固定的 20 条。
--
-- 为什么单独有这么一个文件
-- ------------------------
-- site-check 的第 4 段（小伙伴们）要滚一遍名单，验「滚出视口后冻结」「滚过整份名单
-- 没有空白画布」这些行为，成本随名单长度线性涨。早先的做法是「不足 20 条就补到 20」
-- —— **只补不删**。而套件每跑一次至少会新增 2 条真实提交（带皮肤的那条、只填 TID
-- 的那条，学号带时间戳所以永不重复），于是本地库一路从 20 涨到 234 条，
-- 那一段单个断言的耗时也从 ms 级涨到 3.8 秒（整段 37.8 秒）。
--
-- 所以改成：**跑测试前先清空，再铺固定的 20 条。**
-- 用法（容器内）：`npm run db:seed:local`，然后跑 `node verify/site-check.cjs`。
--
-- 几点说明
-- --------
-- - 学号一律以 `2030` 开头（10 位，符合 worker/register.ts 的 /^\d{10}$/）。
--   site-check 自己的夹具学号是 `sid(n) = '1' + 时间戳后 7 位 + 两位序号`，
--   **首位恒为 1** —— 两边永远不会撞，不会出现 409。
-- - `skin_key` 一律 NULL（走站点内置默认皮肤）。皮肤相关的断言由 site-check
--   临时提交的那两条具名夹具覆盖，不靠这里：一条上传了文件（标签该是「手动上传」），
--   一条只填了 LittleSkin TID（标签该是「LittleSkin」）。所以 `skin_source` 与
--   `littleskin_tid` 这一列在夹具里**留空**才是对的 —— 没皮肤就没有来源可言，
--   硬塞一个值会造出一条「没有皮肤却有来源」的假记录。
-- - 学院给了四个值（不是一个），因为名单页那条断言要确认「卡片下面写的是学院」，
--   单一取值证明不了它读的是这一列。
-- - 姓名与班级填的是明显能识别的占位串：名单页**不该**把它们渲染出来，
--   那两条断言正是拿这些串去反查卡片文本的。

